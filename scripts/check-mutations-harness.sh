#!/usr/bin/env bash
# Сторож мутационного харнесса — проверка того, что он не оставляет мутацию в дереве.
#
# ЗАЧЕМ ЕЩЁ ОДИН УРОВЕНЬ. `check-config-mutations.sh` доказывает, что защиты живы. Но сам
# он ломает рабочее дерево и откатывает — и 13.08.2026 выяснилось, что откат случается
# только в нормальном потоке (#39). Убитый прогон оставил в дереве мутацию, снимавшую
# запрет «//» в пути `GW_ALLOW`, то есть граница безопасности лежала ослабленной, а рядом
# стоял `die` с текстом, утверждавшим обратное. Поймал это не харнесс, а хук.
#
# ⚠ КРИТЕРИЙ, КОГДА НУЖЕН СЛЕДУЮЩИЙ УРОВЕНЬ, — чтобы четвёртый не завёлся по инерции.
# Уровень оправдан, когда у компонента есть путь, который ДАЁТ ГАРАНТИЮ, но почти никогда
# не исполняется в обычном прогоне: «выглядит правильным» там неотличимо от «является
# правильным». Обработчики сигналов и замок — ровно такой путь, в зелёном CI они не
# срабатывают ни разу. У ЭТОГО скрипта такого пути нет: его уборка висит на `trap EXIT`,
# который отрабатывает при любом завершении по построению, а не «пока не забыли». Значит
# сторожа для сторожа сторожей заводить не нужно. Разбор — `docs/PROCESS.md` §5.
#
# ⚠ Проверяем ЗАПУСКОМ, а не чтением кода: рассуждение «обработчик зарегистрирован, значит
# сработает» и есть то, чем харнесс себя успокаивал до #39.
#
# ⚠ SIGKILL не проверяем — он не перехватывается ничем. От него на эфемерном раннере
# защищает то, что рабочий каталог не переживает job.

set -euo pipefail

cd "$(dirname "$0")/.."

HARNESS=scripts/check-config-mutations.sh
# Тот же список, что в самом харнессе. Расхождение означает, что проверка смотрит не на те
# файлы и молча ничего не доказывает, — поэтому оно сверяется случаем 0.
MUTATED=(nginx.conf.template entrypoint.sh Dockerfile scripts/check-crypto.sh)

# Строка, которой харнесс заканчивает УСПЕШНЫЙ прогон. Нужна, чтобы отличить «мы его
# убили» от «он успел доработать сам» — см. случай 1.
DONE_MARK='краснеют своей проверкой'

# Бюджеты щедрые намеренно. При одном постороннем прогоне рядом наблюдались 35 и 63
# секунды на то, что обычно занимает 3: узкий бюджет даёт КРАСНОЕ НА ИСПРАВНОМ КОДЕ, а
# проверка, которая иногда врёт, быстро приучает нажимать «повторить» не читая.
BUDGET_DIRTY=900   # 90 с — дождаться, пока харнесс применит первую мутацию
BUDGET_CLEAN=300   # 30 с — дождаться отката после убийства
BUDGET_GONE=300    # 30 с — дождаться, пока группа процессов умрёт

passed=0
failed=0
ok()  { printf 'ok   %s\n' "$1"; passed=$((passed + 1)); }
bad() { printf 'FAIL %s\n' "$1" >&2; failed=$((failed + 1)); }

LOG=$(mktemp -t harness-run.XXXXXX)
PIDFILE=$(mktemp -t harness-pid.XXXXXX)
OWN_PGID=$(ps -o pgid= -p $$ | tr -d ' ')
BG_PGID=""
# Дерево трогаем ТОЛЬКО если на старте оно было чистым. Иначе `git checkout` в уборке
# стёр бы незакоммиченную работу человека — прежний харнесс в такой ситуации просто
# отказывался работать, и новый сторож не имеет права быть опаснее того, кого сторожит.
STARTED_CLEAN=0

dirty() { [ -n "$(git status --porcelain -- "${MUTATED[@]}")" ]; }

# Жива ли группа. Проверяем перед каждым kill: номер группы переиспользуется ядром, и
# сигнал «в никуда» может достаться постороннему процессу.
group_alive() { [ -n "$BG_PGID" ] && kill -0 -- "-${BG_PGID}" 2>/dev/null; }

kill_group() {
  if [ -n "$BG_PGID" ] && [ "$BG_PGID" != "$OWN_PGID" ] && group_alive; then
    kill -TERM -- "-${BG_PGID}" 2>/dev/null || true
  fi
}

# --- осиротевший .git/index.lock (#44) ----------------------------------------------
# SIGTERM по группе умеет попасть в git ровно между созданием index.lock и его
# удалением. Откат при этом ПРОХОДИТ (дерево чистое, харнесс зелёный), а репозиторий
# остаётся залоченным — и падает не харнесс, а СЛЕДУЮЩАЯ команда человека, уже без
# всякой связи с причиной: `fatal: Unable to create .git/index.lock: File exists`.
# Наблюдалось живьём дважды: один раз из двух прогонов при вводе #42 и ещё раз 15.08.2026
# на ревью PR #76. Гонка узкая, но не редкая.
#
# ⚠ Убираем замок ТОЛЬКО при обоих условиях сразу: файл ПУСТ и убитая группа МЕРТВА.
# Настоящий index.lock живого git непустым не бывает недолго, но группа — наш собственный
# критерий: её номер харнесс знает и её смерти уже дождался. Снять замок у работающего
# git значило бы повредить индекс — сторож не имеет права быть опаснее того, кого
# сторожит. Не подошли условия — не трогаем, а НАЗЫВАЕМ: непонятная ошибка у человека
# хуже лишней строки в логе.
INDEX_LOCK="$(git rev-parse --git-dir)/index.lock"
clear_stale_index_lock() {
  [ -e "$INDEX_LOCK" ] || return 0
  if [ ! -s "$INDEX_LOCK" ] && ! group_alive; then
    rm -f "$INDEX_LOCK"
    printf '     убран осиротевший %s — git был убит между созданием замка и его снятием\n' "$INDEX_LOCK"
  else
    printf 'ВНИМАНИЕ: остался %s — если git не работает, уберите его: rm -f %s\n' \
      "$INDEX_LOCK" "$INDEX_LOCK" >&2
  fi
}

dump_log() {
  printf '     --- лог прогона (%s) ---\n' "$LOG" >&2
  tail -20 "$LOG" 2>/dev/null | sed 's/^/     /' >&2
}

cleanup() {
  local rc=$?
  kill_group
  if [ "$STARTED_CLEAN" = 1 ]; then
    git checkout -- "${MUTATED[@]}" 2>/dev/null || true
  fi
  rm -f "$LOG" "$PIDFILE"
  exit "$rc"
}
trap cleanup EXIT

# Запустить харнесс в СВОЕЙ группе процессов.
#
# ⚠ Идентификатор группы спрашиваем У САМОГО ПОТОМКА через файл, а не угадываем снаружи
# через `ps -o pgid= -p $!`. Причина: `setsid CMD &` ФОРКАЕТ, если вызывающий процесс уже
# лидер группы, и тогда `$!` — pid умирающей заглушки, а не харнесса. Сигнал уходит в
# пустоту, харнесс дорабатывает сам, тест зеленеет НИ РАЗУ НЕ ПРОВЕРИВ обработчики.
# Поведение зависит от окружения: локально сигнал долетал, у одного из проверяющих — нет.
# После `setsid` потомок — лидер сессии, значит его pid и есть pgid; он это знает точно.
start_harness() {
  : > "$PIDFILE"
  # shellcheck disable=SC2016  # одинарные кавычки НАМЕРЕННО: $$/$1/$2 обязан
  # раскрыть внутренний bash уже после setsid, иначе мы подставим свой pid вместо его.
  setsid bash -c 'echo $$ > "$1"; exec bash "$2"' _ "$PIDFILE" "$HARNESS" > "$LOG" 2>&1 &
  for _ in $(seq 1 200); do
    [ -s "$PIDFILE" ] && break
    sleep 0.05
  done
  BG_PGID=$(tr -d ' \n' < "$PIDFILE")
  if [ -z "$BG_PGID" ]; then
    bad "потомок не сообщил свой pid — убивать по группе вслепую нельзя"
    return 1
  fi
  if [ "$BG_PGID" = "$OWN_PGID" ]; then
    # Это означало бы, что setsid не создал новую сессию: kill по группе убил бы нас же
    # (и шаг CI), а мутация осталась бы в дереве.
    bad "потомок в НАШЕЙ группе процессов ($BG_PGID) — отказываюсь убивать"
    BG_PGID=""
    return 1
  fi
  return 0
}

wait_for() {  # wait_for <бюджет> <предикат…>
  local budget=$1; shift
  for _ in $(seq 1 "$budget"); do
    "$@" && return 0
    sleep 0.1
  done
  return 1
}

not_dirty() { ! dirty; }
group_gone() { ! group_alive; }

echo "== 0. Список мутируемых файлов совпадает с харнессом"
if diff <(printf '%s\n' "${MUTATED[@]}" | sort) \
        <(sed -n 's/^MUTATED = (\(.*\))$/\1/p' "$HARNESS" \
          | tr -d ' ' | tr ',' '\n' | sed 's/^\(TPL\)$/nginx.conf.template/;
              s/^\(EP\)$/entrypoint.sh/; s/^\(DF\)$/Dockerfile/;
              s/^\(CR\)$/scripts\/check-crypto.sh/' | sort) > /dev/null; then
  ok "списки совпадают"
else
  bad "список MUTATED в харнессе разошёлся с этим скриптом"
fi

# С этого момента дерево обязано быть чистым, иначе трогать его нельзя.
if dirty; then
  bad "дерево грязное ДО начала — не трогаю его и прекращаю: $(git status --porcelain -- "${MUTATED[@]}" | tr '\n' ' ')"
  printf 'пройдено: %d, провалено: %d\n' "$passed" "$failed"
  exit 1
fi
STARTED_CLEAN=1

echo
echo "== 1. Прогон, убитый SIGTERM на середине, оставляет дерево чистым"
# ⚠ Попыток три, и вот почему. Убийство может НЕ СОСТОЯТЬСЯ: харнесс успевает доработать
# сам, либо сигнал приходит в промежутке между мутациями, когда дерево и так чистое. Тогда
# «дерево чистое» ничего не доказывает — это ложный зелёный, ровно того сорта, с которым
# борется весь этот скрипт. Отличаем по логу: успешный прогон заканчивается своей строкой.
case1_done=0
for attempt in 1 2 3; do
  if ! start_harness; then break; fi
  if ! wait_for "$BUDGET_DIRTY" dirty; then
    bad "попытка $attempt: не дождался мутации за $((BUDGET_DIRTY / 10)) с. Это может быть медленная машина, а не сломанный харнесс"
    dump_log
    kill_group
    break
  fi
  kill_group
  wait_for "$BUDGET_GONE" group_gone || true
  clear_stale_index_lock
  if grep -q "$DONE_MARK" "$LOG" 2>/dev/null; then
    printf '     попытка %d: харнесс успел доработать сам — проверка была бы вхолостую, повторяю\n' "$attempt"
    git checkout -- "${MUTATED[@]}" 2>/dev/null || true
    continue
  fi
  if wait_for "$BUDGET_CLEAN" not_dirty; then
    ok "после SIGTERM дерево чистое — откат отработал (попытка $attempt)"
  else
    bad "после SIGTERM мутация ОСТАЛАСЬ: $(git status --porcelain -- "${MUTATED[@]}" | tr '\n' ' ')"
    dump_log
  fi
  case1_done=1
  break
done
if [ "$case1_done" = 0 ] && [ "$failed" -eq 0 ]; then
  bad "убить харнесс на середине не удалось за три попытки — проверка ничего не доказала"
  dump_log
fi
BG_PGID=""
git checkout -- "${MUTATED[@]}" 2>/dev/null || true

echo
echo "== 2. Второй прогон при живом первом отказывается стартовать"
if start_harness; then
  if ! wait_for "$BUDGET_DIRTY" dirty; then
    bad "не дождался мутации первого прогона за $((BUDGET_DIRTY / 10)) с"
    dump_log
  else
    set +e
    second_out=$(bash "$HARNESS" 2>&1)
    second_rc=$?
    set -e
    if [ "$second_rc" -eq 0 ]; then
      bad "второй прогон завершился успешно — замка нет"
    elif printf '%s' "$second_out" | grep -q "уже идёт"; then
      ok "второй прогон отказался: $(printf '%s' "$second_out" | grep 'уже идёт' | head -1)"
    else
      # Отказ по грязному дереву тоже даёт ненулевой код, но НЕ доказывает замок: без
      # него второй прогон мог бы стартовать в окне между проверкой и первой мутацией.
      bad "второй прогон упал не на замке: $(printf '%s' "$second_out" | head -2 | tr '\n' ' ')"
    fi
  fi
  kill_group
  wait_for "$BUDGET_GONE" group_gone || true
  clear_stale_index_lock
  BG_PGID=""
fi
wait_for "$BUDGET_CLEAN" not_dirty || true
git checkout -- "${MUTATED[@]}" 2>/dev/null || true

echo
printf 'пройдено: %d, провалено: %d\n' "$passed" "$failed"
[ "$failed" -eq 0 ] || exit 1
echo "харнесс не оставляет мутаций в дереве"
