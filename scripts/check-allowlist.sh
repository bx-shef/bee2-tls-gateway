#!/usr/bin/env bash
# Генератор allowlist: проверка того, что из GW_ALLOW получается ровно то, что задумано,
# и что мусор до конфигурации nginx не доезжает.
#
# ЗАЧЕМ. С версии #7 список путей — единственная граница безопасности шлюза — собирается
# генератором в `entrypoint.sh` из строки, которую пишет оператор. Это значит, что теперь
# у границы есть КОД, а у кода — ошибки. Раньше список был литералом в шаблоне и ошибиться
# в нём можно было только руками, теперь ошибиться может генератор.
#
# ⚠ Главное, что здесь утверждается, — что НЕЛЬЗЯ выразить через GW_ALLOW:
#   - подстановку директив nginx (`{`, `}`, `;`, пробелы в пути);
#   - префикс `/`, который превратил бы шлюз в открытый релей к банку;
#   - неизвестный HTTP-метод.
# И что при пустом или битом списке наружу не открывается ничего: отказ по умолчанию
# живёт в шаблоне структурно, генератор физически не может его отменить.
#
# Запускается без Docker: `GW_ALLOW_DUMP=1` заставляет entrypoint выгрузить сгенерированное
# и выйти, не доходя до nginx.
# shellcheck disable=SC2016  # по всему файлу: $uri и подобное — переменные NGINX и части
# заведомо вредоносных строк, которые мы скармливаем генератору. Раскрытие их в bash
# сломало бы ровно то, что проверяется.
set -uo pipefail

cd "$(dirname "$0")/.." || exit 1

# --- замок: два прогона одновременно дают ЛОЖНО КРАСНЫЙ результат -------------------
#
# ⚠ ИЗМЕРЕНО, а не предположено (ревью PR #76): 12 последовательных прогонов — 0 отказов,
# 12 параллельных — 11 отказов, и падает при этом «коллизия меток разводится», то есть
# проверка границы безопасности. Причина не в границе: `entrypoint.sh` пишет сгенерированные
# маршруты в файлы с ФИКСИРОВАННЫМИ именами (`/tmp/crypto-gw.routes*.conf`), их имена
# зашиты и в `nginx.conf.template` как `include`. Два прогона перетирают файлы друг друга,
# и каждый читает чужой дамп.
#
# Почему чиним ЗДЕСЬ, а не в `entrypoint.sh`: в контейнере эта гонка невозможна — у каждого
# свой `/tmp`, а на хосте entrypoint запускают только эти проверки. Менять имена файлов
# значило бы тащить их через `envsubst` в шаблон ради дефекта, которого у изделия нет, —
# и растить объект испытаний (цель 5) на ровном месте.
#
# Почему замок ЖДЁТ, а не отказывает (в отличие от `check-config-mutations.sh`): тот
# мутирует рабочее дерево, и второй прогон обязан отказаться; этот только читает, и ждать
# ему нечем не рискованно. `-w` обязателен: без таймаута ошибка в самом замке дала бы
# зависание вместо внятной строки.
#
# Цена бездействия: ложно красная проверка приучает считать красноту шумом — и настоящую
# поломку границы пропустят следом. Это прямо противоречит цели 3.
_lock="$(git rev-parse --git-dir 2>/dev/null || echo .git)/check-allowlist.lock"
if command -v flock >/dev/null 2>&1; then
  exec {_lock_fd}>"$_lock" || exit 1
  flock -w 120 "$_lock_fd" || { echo "FAIL не дождался замка $_lock" >&2; exit 1; }
else
  # ⚠ Не молча: «нет flock» неотличимо от «есть и работает» — тот же класс тихого
  # вырождения, что и незнакомая переменная у образа (#75). Прогон без замка честен
  # только в одиночку; предупреждение даёт это увидеть, не ломая машины без util-linux.
  echo "ВНИМАНИЕ: flock не найден — прогон без замка, параллельный запуск даст ложные отказы" >&2
fi

pass=0
fail=0

# Стартовые проверки entrypoint требуют связку и хост; берём копию из репозитория.
run() {
  GW_ALLOW_DUMP=1 \
  GW_UPSTREAM_HOST=127.0.0.1 \
  GW_CA_BUNDLE=ca/gossuok-bundle.pem \
  GW_ALLOW="$1" \
  bash entrypoint.sh 2>&1
}

ok() { printf 'ok   %s\n' "$1"; pass=$((pass + 1)); }
bad() { printf 'FAIL %s\n     %s\n' "$1" "$2" >&2; fail=$((fail + 1)); }

# --- принимается и разворачивается верно ---------------------------------------------
out="$(run 'POST =/open-banking-authorize/v1.0/oauth2/token; GET,POST /open-banking/v1.0/')"
if [[ "$out" == *"location = /open-banking-authorize/v1.0/oauth2/token"* ]]; then
  ok 'точное совпадение (=) остаётся точным'
else
  bad 'точное совпадение (=) остаётся точным' "$out"
fi
# Различие «=» и префикса содержательно: токен-эндпоинт — один путь, ресурсный API —
# поддерево. Плоский список префиксов молча расширил бы границу.
if [[ "$out" == *"location /open-banking/v1.0/ {"* ]]; then
  ok 'префикс остаётся префиксом'
else
  bad 'префикс остаётся префиксом' "$out"
fi
if [[ "$out" == *'proxy_pass https://bank$uri$is_args$args;'* ]]; then
  ok 'проксируется НОРМАЛИЗОВАННЫЙ $uri, а не сырой request-target'
else
  bad 'проксируется нормализованный $uri' "$out"
fi
if [[ "$out" == *"limit_except POST { deny all; }"* && "$out" == *"limit_except GET POST { deny all; }"* ]]; then
  ok 'методы переносятся в limit_except'
else
  bad 'методы переносятся в limit_except' "$out"
fi

# --- пустой список: не разрешено ничего, а не разрешено всё ---------------------------
out="$(run '')"
if [[ "$out" == *"--- routes ---"* ]] && ! [[ "$out" == *"proxy_pass"* ]]; then
  ok 'пустой GW_ALLOW не порождает ни одного маршрута'
else
  bad 'пустой GW_ALLOW не порождает маршрутов' "$out"
fi

# --- что должно быть отвергнуто ------------------------------------------------------
reject() {
  local name="$1" value="$2"
  local out rc
  out="$(run "$value")"; rc=$?
  if [[ "$rc" -ne 0 && "$out" == *"FATAL"* ]]; then
    ok "$name"
  else
    bad "$name" "не отвергнуто (rc=$rc): $out"
  fi
}

# Ровно тот случай, ради которого разбор строгий: подстановка директив открыла бы релей.
reject 'подстановка директив nginx отвергается' \
       'GET /x { } location / { proxy_pass https://bank$uri; }'
reject 'путь с пробелом отвергается' 'GET /open banking/'
# ⚠ `;` — разделитель записей, поэтому «путь с ;» отдельным случаем не бывает: строка
# просто распадётся на две записи. Проверяем то, что реально стережёт границу, — что
# вторая половина не проедет как валидная запись.
reject 'обломок после разделителя не становится маршрутом' 'GET /x/;deny'
reject 'префикс «/» отвергается (это был бы открытый релей)' 'GET /'
reject 'неизвестный метод отвергается' 'FETCH /open-banking/v1.0/'
reject 'мусор вместо методов отвергается' 'get,post /open-banking/v1.0/'
# ⚠ Мутация показала, что белый список методов ловит `get,post`, а вот `GET,` проходит
# мимо него (`${methods//,/ }` даёт одно слово GET) — и в конфиг уехало бы
# `limit_except GET, { deny all; }`, которое nginx не примет уже в проде. Держит это
# именно регулярка списка, поэтому у неё должен быть свой случай.
reject 'висячая запятая в списке методов отвергается' 'GET, /open-banking/v1.0/'
reject 'путь без ведущего слеша отвергается' 'GET open-banking/'

# ⚠ ГЛАВНАЯ находка ревью: префикс в nginx — совпадение по НАЧАЛУ СТРОКИ, а не по границе
# сегмента. `location /open-banking` матчит и `/open-banking-admin`, и это уехало бы в банк.
reject 'префикс без завершающего / отвергается (матчил бы соседние пути)' \
       'GET /open-banking'

# Дубликаты роняют nginx с «duplicate location» и уводят контейнер в цикл перезапусков,
# а GW_ALLOW_DUMP этого не покажет — он выходит раньше nginx -t.
reject 'один путь дважды отвергается (был бы duplicate location)' \
       'GET /open-banking/v1.0/; POST /open-banking/v1.0/'
reject 'переопределение /healthz отвергается' 'GET =/healthz'
# ⚠ Сравнения с двумя литералами было мало: `/healthz/` и `=/healthz/` — другие строки, и
# они отдавали поддерево пробы живости банку. Имя занято целиком.
reject 'префикс /healthz/ отвергается (поддерево пробы живости)' 'GET /healthz/'
reject 'точное =/healthz/ отвергается' 'GET =/healthz/'

# ⚠ nginx нормализует путь запроса ДО сопоставления с location, поэтому маршрут с `..`,
# `.` или `//` недостижим в принципе: и дамп, и `nginx -t` покажут его существующим, а в
# проде он отдаст 404. Ложное свидетельство о границе безопасности хуже отказа.
reject 'сегмент .. в пути отвергается (маршрут был бы недостижим)' \
       'GET /open-banking/../admin/'
reject 'сегмент . в пути отвергается' 'GET /open-banking/./v1.0/'
reject 'двойной слеш в пути отвергается' 'GET //open-banking/v1.0/'

# GW_BURST и GW_RATE уходят в конфиг nginx между строго проверяемыми полями.
out="$(GW_BURST='20; deny all' run 'GET /x/')"; rc=$?
if [[ "$rc" -ne 0 && "$out" == *"FATAL"* ]]; then
  ok 'нечисловой GW_BURST отвергается (он уходит в конфиг nginx)'
else
  bad 'нечисловой GW_BURST отвергается' "не отвергнуто (rc=$rc): $out"
fi
out="$(GW_RATE='10r/s; deny all' run 'GET /x/')"; rc=$?
if [[ "$rc" -ne 0 && "$out" == *"FATAL"* ]]; then
  ok 'нечисловой GW_RATE отвергается (он уходит в конфиг nginx)'
else
  bad 'нечисловой GW_RATE отвергается' "не отвергнуто (rc=$rc): $out"
fi

# ⚠ НОЛЬ — отдельный случай, и он не выводится из «числовое значение годится». nginx
# отвергает и `burst=0`, и `rate=0r/s`: у него нулевой всплеск выражается ОТСУТСТВИЕМ
# параметра, а нулевая скорость не выражается никак. Регулярка `^[0-9]+$` ноль пропускала,
# и отказ приезжал позже — английской строкой `[emerg] invalid burst value` от `nginx -t`
# вместо названной причины. Измерено красным job `image` в PR #143.
out="$(GW_BURST=0 run 'GET /x/')"; rc=$?
if [[ "$rc" -ne 0 && "$out" == *"FATAL"* ]]; then
  ok 'GW_BURST=0 отвергается до nginx (nginx не примет burst=0)'
else
  bad 'GW_BURST=0 отвергается до nginx' "не отвергнуто (rc=$rc): $out"
fi
out="$(GW_RATE=0 run 'GET /x/')"; rc=$?
if [[ "$rc" -ne 0 && "$out" == *"FATAL"* ]]; then
  ok 'GW_RATE=0 отвергается до nginx (скорость обязана быть положительной)'
else
  bad 'GW_RATE=0 отвергается до nginx' "не отвергнуто (rc=$rc): $out"
fi

# Разные пути не должны получить одинаковую метку: иначе два эндпоинта неразличимы в логе.
out="$(run 'GET /a.b/; GET /a_b/')"
if [[ "$(printf '%s' "$out" | grep -c ' a-b;$')" -le 1 ]]; then
  ok 'коллизия меток разводится, а не оставляется молча'
else
  bad 'коллизия меток разводится' "$out"
fi
# ⚠ Один суффикс уникальности не даёт: он сам может совпасть с меткой уже разобранного
# пути. Здесь `/abc./` коллизирует с `/abc/`, а напрашивающийся суффикс занят `/abc-1/` —
# значит проверять надо и суффиксированную метку, а не только исходную.
out="$(run 'GET /abc/; GET /abc-1/; GET /abc./')"
labels="$(printf '%s' "$out" | sed -n 's/^ *~\^.* \([A-Za-z0-9-]*\);$/\1/p')"
if [[ "$(printf '%s\n' "$labels" | sort -u | wc -l)" -eq 3 ]]; then
  ok 'метки уникальны и когда сам суффикс уже занят'
else
  bad 'метки уникальны и когда сам суффикс уже занят' "получилось: $(printf '%s' "$labels" | tr '\n' ' ')"
fi

# ⚠ `=/a/` и `/a/` — ДВА РАЗНЫХ location (точный путь и поддерево), а не дубликат. Ключ
# дедупа со строчным пробелом (`= /a/`) ломался о собственный разделитель, и отказ зависел
# от порядка записей: точное первым — ложный FATAL, префикс первым — тишина.
for order in 'GET =/a/; POST /a/' 'POST /a/; GET =/a/'; do
  out="$(run "$order")"
  if [[ "$out" == *"location = /a/ {"* && "$out" == *"location /a/ {"* ]]; then
    ok "точное и префиксное «/a/» сосуществуют ($order)"
  else
    bad "точное и префиксное «/a/» сосуществуют ($order)" "$out"
  fi
done

# `=/` — точное совпадение с корнем. Это ОДИН путь, а не поддерево, поэтому релеем не
# становится и запрещать его незачем: проверяем, что различие не потеряно.
out="$(run 'GET =/')"
if [[ "$out" == *"location = / {"* ]]; then
  ok 'точное «=/» разрешено (это один путь, а не поддерево)'
else
  bad 'точное «=/» разрешено' "$out"
fi

# ---------------------------------------------------------------------------
# Рекомендованный список из README — прогоняется ОТТУДА, а не переписывается сюда.
#
# ⚠ Зачем. README даёт оператору строку GW_ALLOW для боевого контура (маршруты DCR,
# #64). Это единственный опубликованный «скопируй и запусти» рецепт ГРАНИЦЫ
# БЕЗОПАСНОСТИ, и до этой проверки его не сторожило ничто: разъедься генератор с
# документом — CI остался бы зелёным, а оператор открыл бы себе не то, что прочитал.
# Приём тот же, которым сторожится команда диагностики в PROCESS.md §4: берём текст
# из документа и исполняем его, чтобы копия не могла сгнить молча.
README="$(cd "$(dirname "$0")/.." && pwd)/README.md"
readme_list="$(
  sed -n '/GW_ALLOW_DCR_BEGIN/,/GW_ALLOW_DCR_END/p' "$README" \
    | sed -n "s/^-e GW_ALLOW='\(.*\)'$/\1/p"
)"
if [ -z "$readme_list" ]; then
  bad 'список DCR извлекается из README' 'не нашёл строку между GW_ALLOW_DCR_BEGIN/END'
else
  ok 'список DCR извлекается из README'
  out="$(run "$readme_list")"
  # Каждая строка: «что ищем в дампе» + «человеческое имя». Проверяются ровно те
  # утверждения, которые README печатает в своей таблице: вид совпадения и методы.
  while IFS='|' read -r needle name; do
    [ -n "$needle" ] || continue
    if [[ "$out" == *"$needle"* ]]; then
      ok "README-список: $name"
    else
      bad "README-список: $name" "не нашёл в дампе: $needle"
    fi
  done <<'CASES'
location = /open-banking-dcr/v1.0/register {|создание приложения — ТОЧНЫЙ путь
location /open-banking-dcr/v1.0/register/ {|чтение регистрации — поддерево
location = /open-banking-dcr/v1.0/oidcdiscovery {|oidcdiscovery — ТОЧНЫЙ путь
CASES
  # Методы: README обещает POST только на создание и GET только на чтение. Без этой
  # проверки список мог бы открыть POST на поддерево и остаться «совпадающим».
  post_block="$(printf '%s' "$out" | sed -n '/location = \/open-banking-dcr\/v1.0\/register {/,/}/p')"
  if [[ "$post_block" == *"limit_except POST {"* ]]; then
    ok 'README-список: на создании разрешён только POST'
  else
    bad 'README-список: на создании разрешён только POST' "$post_block"
  fi
  read_block="$(printf '%s' "$out" | sed -n '/location \/open-banking-dcr\/v1.0\/register\/ {/,/}/p')"
  if [[ "$read_block" == *"limit_except GET {"* ]]; then
    ok 'README-список: на чтении регистрации разрешён только GET'
  else
    bad 'README-список: на чтении регистрации разрешён только GET' "$read_block"
  fi
  # Умолчание внутри рекомендации: рецепт обязан СОДЕРЖАТЬ прежние два маршрута.
  # Потеряется один — у скопировавшего встанет работающая интеграция, и README
  # предупреждает об этом словами. Пусть предупреждение будет ещё и проверкой.
  if [[ "$out" == *"location = /open-banking-authorize/v1.0/oauth2/token {"* \
     && "$out" == *"location /open-banking/v1.0/ {"* ]]; then
    ok 'README-список: прежние два маршрута на месте'
  else
    bad 'README-список: прежние два маршрута на месте' "$out"
  fi

  # ⚠ ПОРЯДОК ЗАПИСЕЙ — ЧАСТЬ РЕЦЕПТА, и до ревью PR #76 его не держало ничто.
  # Метки `route=` строятся из пути, у двух записей DCR основа совпадает, и суффикс `-1`
  # достаётся ТОЙ, ЧТО В СПИСКЕ ВТОРАЯ. README печатает конкретный пример строки лога и
  # учит фильтровать мониторинг по этой метке. Поменяй кто-нибудь записи местами — все
  # проверки выше остались бы зелёными (они смотрят на `location`, а не на карту меток),
  # а метка в примере стала бы принадлежать другому маршруту, и фильтр в чужом дашборде
  # начал бы показывать не тот трафик. Молча. Показано прогоном при вводе.
  while IFS='|' read -r needle name; do
    [ -n "$needle" ] || continue
    if [[ "$out" == *"$needle"* ]]; then
      ok "README-список: $name"
    else
      bad "README-список: $name" "не нашёл в карте меток: $needle"
    fi
  done <<'ROUTEMAP'
/open-banking-dcr/v1.0/register open-banking-dcr-v1-0-register;|метка создания — без суффикса
open-banking-dcr-v1-0-register-1;|метка чтения регистрации — с суффиксом -1
ROUTEMAP
fi

# ⚠ УМОЛЧАНИЕ ГОНЯЕТСЯ ТОЖЕ — БЕЗ GW_ALLOW ВОВСЕ, и до ревью PR #76 этого не делал
# ни один быстрый тест: все вызовы run() передают явное значение, и ветка `${GW_ALLOW-…}`
# исполнялась только в смоуке job `image`, необязательном чеке. Тестировщик показал
# прогоном: правь умолчание как угодно — здесь всё оставалось зелёным. А умолчание — это
# то, что получает КАЖДЫЙ, кто ничего не настраивал; его метки уже опубликованы.
out_default="$(
  GW_ALLOW_DUMP=1   GW_UPSTREAM_HOST=127.0.0.1   GW_CA_BUNDLE=ca/gossuok-bundle.pem   bash entrypoint.sh 2>&1
)"
while IFS='|' read -r needle name; do
  [ -n "$needle" ] || continue
  if [[ "$out_default" == *"$needle"* ]]; then
    ok "умолчание: $name"
  else
    bad "умолчание: $name" "не нашёл в дампе: $needle"
  fi
done <<'DEFAULTS'
location = /open-banking-authorize/v1.0/oauth2/token {|токен-эндпоинт, точный путь
location /open-banking/v1.0/ {|ресурсный API, поддерево
open-banking-authorize-v1-0-oauth2-token;|метка токена — без суффикса
