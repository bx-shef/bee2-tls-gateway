# ⚠ Строка про число маршрутов — ЭТО КОНТРАКТ С ОПЕРАТОРОМ, а не украшение лога.
# README учит: «нет этой строки при старте — сборка старая и переменную не знает». Так
# потребитель отличает запинённый по digest образ без поддержки `GW_ALLOW` от неверного
# списка; на этом различении он потерял полдня (#75, #64). Переименуй кто-нибудь строку —
# рецепт распознавания молча перестал бы работать, а узнали бы об этом снова в бою.
out_any="$(run 'GET /open-banking/v1.0/')"
if [[ "$out_any" == *"allowlist: разрешено маршрутов —"* ]]; then
  ok 'строка «allowlist: разрешено маршрутов — N» печатается (по ней узнают старую сборку)'
else
  bad 'строка «allowlist: разрешено маршрутов — N» печатается' "$out_any"
fi

# ⚠ Отказ на переносе строки внутри значения — тоже контракт: README учит раскладывать
# список в docker-compose свёрнутым скаляром `>-` ИМЕННО потому, что блочный `|` оставит
# перенос и контейнер не встанет. Утверждение проверяемое, значит должно проверяться:
# смягчи кто-нибудь разбор до «схлопнем пробелы» — рекомендация станет суеверием.
out_nl="$(run "$(printf 'GET,\nPOST /open-banking/v1.0/')")"
if [[ "$out_nl" == *"FATAL"* && "$out_nl" == *"не похожи на список вида"* ]]; then
  ok 'перенос строки в поле методов — фатальный отказ, а не молчаливое склеивание'
else
  bad 'перенос строки в поле методов — фатальный отказ' "$out_nl"
fi

