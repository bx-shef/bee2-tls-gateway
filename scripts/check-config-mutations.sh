#!/usr/bin/env bash
# Мутационная проверка для scripts/check-config.sh — сторож сторожа.
#
# ЗАЧЕМ. Проверка конфигурации, которая никогда не краснеет, неотличима от проверки,
# которая работает: обе печатают «ok» и обе зелёные в CI. Разница видна только тогда,
# когда что-то ломают — то есть на боевом сервере. Здесь мы ломаем нарочно: каждая
# мутация вносит в `nginx.conf.template` или `entrypoint.sh` ровно ту порчу, против
# которой написана соответствующая проверка, и ОБЯЗАНА покраснеть — причём ИМЕННО своей
# проверкой. Покраснела чужой — значит своя мертва, а её работу случайно делает соседка.
#
# Так был найден мёртвый сторож: проверка «переменные nginx не попали в список envsubst»
# собирала список регуляркой `\$\{([A-Z0-9_]+)\}` — только ПРОПИСНЫЕ имена. Все переменные
# nginx строчные ($status, $uri, $args), так что искомое в список не попадало никогда и
# проверка не могла покраснеть в принципе. Мутации 5a/5b держат её живой.
#
# ⚠ «мутация не применилась» — тоже провал, а не пропуск. Если шаблон отформатировали и
# паттерн перестал совпадать, проверка молча перестала бы что-либо доказывать; лучше
# красный CI и поправленный паттерн.
#
# Дерево должно быть чистым по мутируемым файлам: откат идёт через `git checkout`.
set -euo pipefail

cd "$(dirname "$0")/.."

python3 - <<'PY'
import atexit
import fcntl
import os
import re
import signal
import subprocess
import sys
import tempfile

TPL = "nginx.conf.template"
EP = "entrypoint.sh"
DF = "Dockerfile"
CR = "scripts/check-crypto.sh"

# Всё, что мутируем, обязано откатываться. Забыть файл здесь — значит оставить мутацию
# в рабочем дереве и увести следующего в разбор несуществующей поломки.
#
# ⚠ README.md здесь БЫЛ и был убран по итогам ревью #45. Мутация «убрать пример лога из
# README» требовала держать его в этом списке, а список требует чистоты по своим файлам на
# старте прогона. По правилам проекта документация правится В ТОМ ЖЕ PR, что и код, — то
# есть README грязен ровно тогда, когда прогон и нужен, и оба скрипта отказывались
# работать. Проверка, которую нельзя запустить в разгар работы, перестаёт запускаться
# вовсе. Вместо этого сверка README↔код сделана равенством множеств, где источник истины —
# код: пустой README теперь не «нечему разойтись», а прямое расхождение.
MUTATED = (TPL, EP, DF, CR)


# ⚠ Таймауты у ОБОИХ подпроцессов — #44. Зависший вызов (ждёт ввода, бесконечный цикл)
# останавливал прогон С АКТИВНОЙ МУТАЦИЕЙ В ДЕРЕВЕ и взятым замком — ровно состояние #39,
# только приходим мы в него не убийством, а тишиной: capture_output прячет вывод, и со
# стороны зависший прогон неотличим от медленного. Локально это замок + ослабленная
# граница в дереве до чьего-то `git status`; в CI — десять минут раннера и диагноз
# «job отвалился по таймауту» вместо имени вставшей проверки.
GIT_TIMEOUT = 10       # git локальный; секунды — уже патология
CHECK_TIMEOUT = 120    # весь прогон сторожа укладывается в ~25 с; запас пятикратный


def git(*args):
    try:
        return subprocess.run(["git", *args], capture_output=True, text=True,
                              timeout=GIT_TIMEOUT)
    except subprocess.TimeoutExpired:
        # Заглушка с ненулевым кодом, а не исключение: restore() уже проверяет код
        # возврата и жалуется громко, а исключение из atexit-отката умерло бы молча.
        return subprocess.CompletedProcess(
            ["git", *args], 124, "",
            f"git {' '.join(args)} не завершился за {GIT_TIMEOUT} с — убит по таймауту")


def restore():
    """Вернуть мутируемые файлы к состоянию HEAD.

    ⚠ Код возврата ПРОВЕРЯЕТСЯ и жалоба идёт в stderr. `git checkout` умеет не сработать —
    например, проиграв гонку за `.git/index.lock` соседнему процессу, который читает
    `git status` в цикле (так делает scripts/check-mutations-harness.sh). Молчаливый
    неоткат — это ровно #39 с другой стороны: мутация остаётся, а прогон идёт дальше как
    ни в чём не бывало.

    ⚠ ОДИН повтор после уборки СВОЕГО осиротевшего замка — не «ещё раз на всякий случай».
    SIGTERM по группе (харнесс-сторож так и убивает) достаётся и НАШЕМУ дочернему git:
    если сигнал пришёл, пока git держал index.lock, замок остаётся, и первый же повторный
    checkout — включая вот этот, из обработчика сигнала, — падает 128 «File exists» об
    останки собственного ребёнка. Ровно это показал CI 15.08.2026 (PR #77, шаг харнесса):
    жертва честно пыталась откатиться и не смогла, а прибрать замок было некому.
    Условие уборки то же, что у сторожа: замок ПУСТ. Живой чужой git тут исключён надёжнее,
    чем у сторожа: мы внутри обработчика сигнала собственного процесса, наши дочерние git
    только что убиты тем же сигналом по группе, а два прогона одновременно исключает flock.
    """
    p = git("checkout", "--", *MUTATED)
    if p.returncode != 0:
        # путь берём у git, а не строим руками: в worktree .git — файл, а не каталог
        gd = git("rev-parse", "--git-dir").stdout.strip() or ".git"
        lock = os.path.join(gd, "index.lock")
        if os.path.exists(lock) and os.path.getsize(lock) == 0:
            try:
                os.unlink(lock)
            except OSError:
                pass
            else:
                print(f"убран осиротевший {lock} (git был убит с замком в руках), повторяю откат",
                      file=sys.stderr)
                p = git("checkout", "--", *MUTATED)
    if p.returncode != 0:
        print(
            f"FAIL откат не сработал (git checkout вернул {p.returncode}): "
            f"{p.stderr.strip()[:200]}",
            file=sys.stderr,
        )


def _on_signal(signum, _frame):
    """Откатить мутацию и выйти кодом оболочки (128 + номер сигнала)."""
    restore()
    # os._exit, а не sys.exit: мы внутри обработчика, и раскрутка стека может пройти
    # через subprocess, который перехватит исключение. Откат уже сделан строкой выше.
    os._exit(128 + signum)


def sub(path, pattern, repl):
    """Заменить первое совпадение; False, если паттерн не совпал.

    re.M — чтобы `^`/`$` означали границы СТРОКИ: пины задаются построчно (`ARG NAME=...`),
    и без этого флага такой паттерн молча не совпадёт, а мутация превратится в пропуск.
    """
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    new, count = re.subn(pattern, repl, text, count=1, flags=re.M)
    if count == 0:
        return False
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(new)
    return True


def run_checks(script="scripts/check-config.sh", timeout=CHECK_TIMEOUT):
    """rc None означает «проверка ЗАВИСЛА» — это отдельный исход, не красный и не зелёный.

    ⚠ TimeoutExpired ловится КАК ПРОВАЛ ПРОВЕРКИ, а не как крах скрипта: прогон обязан
    дойти до отката и до отчёта, называющего активную мутацию, — иначе таймаут в CI
    читается так же плохо, как раньше читалось зависание.
    """
    try:
        p = subprocess.run(["bash", script], capture_output=True, text=True,
                           timeout=timeout)
    except subprocess.TimeoutExpired as exc:
        # ⚠ exc.stdout здесь БАЙТЫ, несмотря на text=True, — особенность CPython
        # (bpo-34572). Первая редакция клеила их со строкой и падала TypeError ровно на
        # реалистичном зависании (проверка успела напечатать ok-строки и встала) — то
        # есть крашилась на том самом входе, ради которого написана. Нашло ревью,
        # воспроизведя прогоном; самопроверка ниже теперь печатает вывод ДО зависания,
        # чтобы этот путь не остался снова непокрытым.
        def _txt(x):
            if x is None:
                return ""
            return x.decode("utf-8", "replace") if isinstance(x, bytes) else x
        tail = (_txt(exc.stdout) + _txt(exc.stderr)).splitlines()[-3:]
        return None, f"ЗАВИСЛА: {script} не завершился за {timeout} с; хвост: {tail}"
    return p.returncode, p.stdout + p.stderr


results = []


def mutate(name, apply_fn, want, script="scripts/check-config.sh"):
    """want — фрагмент имени проверки, которая ОБЯЗАНА покраснеть на этой мутации.

    script — какой сторож обязан её поймать. Мутация, пойманная ЧУЖИМ сторожем, здесь
    считается провалом: значит свой мёртв, а его работу делает соседний по случайности.
    """
    restore()
    if not apply_fn():
        results.append(("СЛОМ", name, "мутация не применилась: паттерн не совпал с файлом"))
        restore()
        return
    rc, out = run_checks(script)
    fails = [ln for ln in out.splitlines() if ln.startswith("FAIL")]
    if rc is None:
        # Именно ИМЯ активной мутации: без него таймаут читается как «что-то встало».
        results.append(("СЛОМ", name, f"проверка зависла при активной мутации «{name}»: {out}"))
    elif rc == 0:
        results.append(("СЛОМ", name, "ЗЕЛЁНЫЙ — проверка не ловит эту поломку"))
    elif not any(want in ln for ln in fails):
        results.append(("СЛОМ", name, f"красный, но не проверкой «{want}»: {fails}"))
    else:
        results.append(("ok", name, "; ".join(fails)))
    restore()


# --- замок: два прогона одновременно дают ЛОЖНЫЕ выводы ----------------------------
#
# Проверка «дерево чистое» ниже стоит на старте, но между ней и первой мутацией есть
# окно: второй прогон успевает увидеть чистое дерево. Дальше они мутируют и откатывают
# друг друга вперемешку, и результат непредсказуем — включая «покраснела не та проверка»
# и «мутация не применилась». То есть инструмент, доказывающий живость защит, сам начинает
# врать. Замок берём ПЕРВЫМ делом, до проверки дерева: иначе второй прогон отвалился бы с
# сообщением про грязное дерево, и настоящая причина осталась бы неназванной.
#
# Файл замка — в каталоге .git: он есть всегда, никогда не коммитится и не попадёт в образ.
# Путь спрашиваем у git, а не пишем «.git» литералом: в worktree это файл, а не каталог.
_git_dir = git("rev-parse", "--git-dir").stdout.strip() or ".git"
_lock_path = os.path.join(_git_dir, "check-config-mutations.lock")
_lock_fh = open(_lock_path, "w")  # noqa: SIM115 — держим открытым до конца процесса
try:
    fcntl.flock(_lock_fh, fcntl.LOCK_EX | fcntl.LOCK_NB)
except OSError:
    # Замок снимается ядром при завершении процесса, в том числе убитого SIGKILL, —
    # поэтому «занят» здесь означает именно живой прогон, а не мусор от прошлого.
    sys.exit(f"FAIL мутационный прогон уже идёт (замок {_lock_path}) — прерываю")

# ⚠ Код возврата — РАНЬШЕ вывода, и это не педантизм: git-обёртка при таймауте
# возвращает rc=124 с ПУСТЫМ stdout, а пустой stdout здесь читался как «дерево чистое».
# Ревью показало прогоном с зависающим git в PATH: предохранитель пропускал грязное
# дерево молча, и первый restore() затирал несохранённую работу в MUTATED-файлах без
# единого предупреждения. Зависший git status — не экзотика: сетевая ФС, чужой замок.
_st = git("status", "--porcelain", "--", *MUTATED)
if _st.returncode != 0:
    sys.exit(f"FAIL git status не отработал (rc={_st.returncode}): {_st.stderr.strip()} — "
             "состояние дерева НЕИЗВЕСТНО, прерываю")
if _st.stdout.strip():
    sys.exit(
        "FAIL мутируемые файлы изменены — откат идёт через git, прерываю.\n"
        "  Если прогон до этого убивали (таймаут, Ctrl-C, SIGKILL), мутация могла остаться\n"
        "  в дереве. Вернуть как было:\n"
        f"    git checkout -- {' '.join(MUTATED)}"
    )

# --- откат при ЛЮБОМ выходе, а не только в нормальном потоке (#39) ------------------
#
# Мутация живёт в рабочем дереве считаные миллисекунды, но между её применением и
# откатом прогон можно убить: таймаут агента, Ctrl-C, SIGTERM от оболочки. Раньше
# restore() стоял только в нормальном потоке, и убитый прогон оставлял границу
# безопасности ослабленной — ровно так 13.08.2026 в дереве нашлась мутация, снимавшая
# запрет «//» в пути. Файл при этом выглядит обычно: одна строка условия.
#
# ⚠ РЕГИСТРИРУЕМ ТОЛЬКО ЗДЕСЬ — после замка и проверки дерева, а не рядом с restore().
# Иначе второй прогон, отвалившийся на замке, на своём выходе позвал бы restore() и
# затёр АКТИВНУЮ мутацию первого: тот увидел бы «мутация не применилась» или, хуже,
# ложный зелёный. Сторож, портящий работу другого сторожа, — ровно та болезнь, от
# которой лечит #39.
#
# ⚠ Почему atexit + обработчики, а НЕ try/finally вокруг всего тела, как предлагает #39.
# Тело — двести строк верхнего уровня; заворачивание в try потребовало бы переотступить
# их целиком, а это именно та правка, в которой легко потерять строку и не заметить.
# Покрытие то же: atexit ловит нормальный выход, sys.exit и необработанное исключение,
# обработчики — сигналы.
#
# ⚠ SIGKILL не перехватывается ничем. От него спасает только внешняя проверка — она
# стоит выше (дерево должно быть чистым) и в job `ci`.
atexit.register(restore)
for _sig in (signal.SIGINT, signal.SIGTERM, signal.SIGHUP):
    signal.signal(_sig, _on_signal)

# ⚠ Самопроверка таймаута идёт ПЕРВОЙ, и у неё тот же профиль, что у обработчиков
# сигналов: путь, который в зелёном прогоне не исполняется ни разу. Заведомо зависающий
# скрипт с коротким таймаутом обязан вернуться rc=None, а не повесить прогон, — иначе вся
# правка #44 держится на слове. Две секунды за то, чтобы мёртвая ветка не жила годами.
# ⚠ echo ДО sleep обязателен: он гонит вывод в exc.stdout и покрывает путь с байтами
# (bpo-34572), на котором первая редакция крашилась. Молча зависающий скрипт этот путь
# не исполняет — самопроверка была бы зелёной при живом краше.
# ⚠ unlink в finally: упади run_checks по любой причине, мусор в /tmp не останется.
# Осиротевший от таймаута sleep 999 (python не убивает потомков bash) — принятая мелочь:
# на эфемерном раннере он умирает с job, на машине разработчика догорает сам.
with tempfile.NamedTemporaryFile("w", suffix=".sh", delete=False) as _hang:
    _hang.write("#!/bin/sh\necho 'вывод до зависания'\nsleep 999\n")
try:
    _rc, _out = run_checks(_hang.name, timeout=2)
finally:
    os.unlink(_hang.name)
if _rc is not None:
    sys.exit(f"FAIL самопроверка таймаута: зависший скрипт вернул rc={_rc}, а не None")
if "вывод до зависания" not in _out:
    sys.exit(f"FAIL самопроверка таймаута: вывод до зависания потерян: {_out}")
# ⚠ НЕ в results: там считаются мутации, и служебная запись завышала счётчик — скрипт
# печатал «все 70 мутаций», имея 69. Нашли двое из пяти на ревью, порознь.
print(f"ok   таймаут ловит зависшую проверку и доносит вывод: {_out.split(';')[0]}")

for script in ("scripts/check-config.sh", "scripts/check-pins.sh",
               "scripts/check-allowlist.sh"):
    rc, out = run_checks(script)
    if rc is None:
        sys.exit(f"FAIL базовая линия у {script} ЗАВИСЛА ещё до мутаций:\n{out}")
    if rc != 0:
        sys.exit(f"FAIL базовая линия КРАСНАЯ у {script} — чинить его, а не мутации:\n{out}")
results.append(("ok", "базовая линия без мутаций", "зелёная у всех сторожей"))

# --- envsubst: список переменных против плейсхолдеров шаблона ---------------------
mutate("плейсхолдер шаблона отсутствует в списке envsubst",
       lambda: sub(TPL, r"client_max_body_size 64k;", "client_max_body_size ${GW_MAX_BODY};"),
       "каждый плейсхолдер шаблона есть в списке envsubst")

mutate("в списке envsubst переменная, которой нет в шаблоне",
       lambda: sub(EP, r"\$\{GW_ERROR_LOG_LEVEL\}'", "${GW_ERROR_LOG_LEVEL} ${GW_GHOST}'"),
       "нет переменных, которых нет в шаблоне")

mutate("подставляемая переменная без дефолта в entrypoint",
       lambda: (sub(TPL, r"client_max_body_size 64k;", "client_max_body_size ${GW_MAX_BODY};")
                and sub(EP, r"\$\{GW_ERROR_LOG_LEVEL\}'",
                        "${GW_ERROR_LOG_LEVEL} ${GW_MAX_BODY}'")),
       "у каждой подставляемой переменной есть дефолт")

# Обе формы: envsubst понимает и `${name}`, и `$name`.
mutate("переменная nginx ${status} попала в список envsubst",
       lambda: sub(EP, r"envsubst '", "envsubst '${status} "),
       "переменные nginx не попали")

mutate("переменная nginx $uri попала в список envsubst (без скобок)",
       lambda: sub(EP, r"envsubst '", "envsubst '$uri "),
       "переменные nginx не попали")

# --- лог не несёт путь запроса ----------------------------------------------------
mutate("$request_uri добавлен в формат лога",
       lambda: sub(TPL, r"rt=\$request_time", "path=$request_uri rt=$request_time"),
       "формат лога не несёт путь")

# --- открытый текст не покидает память процесса на носитель ------------------------
# ⚠ Несколько мутаций на каждую из трёх директив, и очевидная из них только первая (число
# здесь не называем: его печатает сам прогон, а вписанное в текст устаревает молча).
# Остальные — ровно те
# способы, которыми проверка этого класса умирает, оставаясь зелёной:
#   • директива на месте, но с ненулевым размером — конфиг читается «ограничение стоит», а
#     мегабайт выписки на носитель всё равно ложится;
#   • ВТОРОЕ вхождение ниже первого, во вложенном контексте: в nginx выигрывает самое
#     вложенное, конфиг при этом валиден (`nginx -t` проходит), а `re.search` видит только
#     самое левое. Эту мутацию принесла панель ревью — первая редакция проверки её
