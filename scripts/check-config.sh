#!/usr/bin/env bash
# Проверки конфигурации шлюза — та часть, которая является чистым текстом и потому
# проверяема без Docker, OpenSSL и банка.
#
# ЗАЧЕМ. `nginx.conf.template` рендерится в `entrypoint.sh` через `envsubst` с ЯВНЫМ списком
# переменных. Этот список — рукописная копия плейсхолдеров шаблона, и ничто не заставляет их
# совпадать: `envsubst` молча оставит не перечисленный `${GW_NEW}` в выводе как обычный текст,
# и ошибка вылезет падением `nginx -t` НА СТАРТЕ КОНТЕЙНЕРА — на сервере, во время выката, —
# а не в pull request. Остальное про образ стерегут гейты внутри Dockerfile; эта щель
# проверяется здесь, поэтому здесь и проверяется.
#
# ⚠ Каждая проверка ниже держит инвариант, названный в README: список путей — единственная
# граница безопасности, лог не несёт пути (в пути ездит номер счёта), проверка апстрима
# включена, forward secrecy предпочтительнее переноса ключа.
#
# ⚠ С #42 скрипт стережёт ВТОРУЮ область — секцию 0 `entrypoint.sh` (самотест криптостека,
# проверки 10) — и ради неё читает ТРЕТИЙ файл, `README.md`: строки успеха самотеста обещаны
# там оператору, а значит это контракт, который может разойтись с кодом. Он и разошёлся —
# разбор в `docs/PROCESS.md` §5.
#
# ⚠ ГЛАВНЫЙ УРОК проверок 10, применимый ко всему файлу: сверка на ВХОЖДЕНИЕ ПОДСТРОКИ
# доказывает, что текст написан, и ничего — о том, что он работает. Первая редакция тех
# проверок пропускала пять разных обходов, каждый оставлял её зелёной при мёртвом самотесте.
# Сверяйте оператор целиком и дословно, а что дословностью не ловится — отдельной проверкой.
set -euo pipefail

cd "$(dirname "$0")/.."

TEMPLATE=nginx.conf.template
ENTRYPOINT=entrypoint.sh
README=README.md
HEALTHCHECK=healthcheck.sh

for f in "$TEMPLATE" "$ENTRYPOINT" "$README" "$HEALTHCHECK"; do
  [ -r "$f" ] || { echo "FAIL нет файла $f" >&2; exit 1; }
done

TEMPLATE="$TEMPLATE" ENTRYPOINT="$ENTRYPOINT" README="$README" HEALTHCHECK="$HEALTHCHECK" python3 - <<'PY'
import os
import re
import sys

template = open(os.environ["TEMPLATE"], encoding="utf-8").read()
entrypoint = open(os.environ["ENTRYPOINT"], encoding="utf-8").read()
readme = open(os.environ["README"], encoding="utf-8").read()
healthcheck = open(os.environ["HEALTHCHECK"], encoding="utf-8").read()

# Код entrypoint.sh без строк-комментариев. Нужен проверкам 9: слова `st alg` и `st rng`
# встречаются в комментариях выше по файлу (замеры времени), и поиск по всему тексту нашёл
# бы комментарий вместо вызова — то есть проверка утверждала бы про прозу, а не про код.
entrypoint_code = re.sub(r"^\s*#.*$", "", entrypoint, flags=re.M)

failures = []


def check(name, ok, detail=""):
    if ok:
        print(f"ok   {name}")
    else:
        print(f"FAIL {name}: {detail}", file=sys.stderr)
        failures.append(name)


# Плейсхолдеры, которые шаблон ждёт от envsubst.
placeholders = set(re.findall(r"\$\{(GW_[A-Z0-9_]+)\}", template))

# Список, реально переданный в envsubst — аргумент SHELL-FORMAT этого вызова.
call = re.search(r"envsubst\s+'([^']+)'", entrypoint)
if not call:
    print("FAIL entrypoint.sh: вызов envsubst с кавычным списком не найден", file=sys.stderr)
    sys.exit(1)
# ⚠ Имена ловим ЛЮБЫЕ, а не только ПРОПИСНЫЕ, и обе формы — `${NAME}` и `$NAME`
#   (envsubst принимает обе). Прежняя регулярка `\$\{([A-Z0-9_]+)\}` пропускала ровно то,
#   ради чего написана проверка 4 ниже: переменные nginx СТРОЧНЫЕ ($status, $uri, $args),
#   так что попади они в SHELL-FORMAT — в allowlist они бы не попали, и проверка не
#   покраснела бы НИКОГДА. Проверено запуском envsubst (nginx:1.27-alpine):
#     envsubst '${status} ${GW_LISTEN}'  →  log_format gw "status= rt=$request_time";
#   nginx такой конфиг принимает и стартует, поле в логе просто исчезает — то есть без
#   этой проверки поломка молчаливая, и найдётся она по пустой колонке в агрегации.
allowlist = set(re.findall(r"\$\{?([A-Za-z_][A-Za-z0-9_]*)\}?", call.group(1)))
# Проверки 1 и 2 — про наши собственные переменные; всё, что не GW_, разбирает проверка 4,
# иначе одна и та же чужая переменная краснела бы дважды разными словами.
gw_allowlist = {v for v in allowlist if v.startswith("GW_")}

# 1. Промах оставит в отрендеренном конфиге буквальный `${GW_…}`, и nginx не стартует.
missing = sorted(placeholders - gw_allowlist)
check("каждый плейсхолдер шаблона есть в списке envsubst", not missing, f"нет в списке: {missing}")

# 2. Безвредно в рантайме, но значит, что переменную выкинули из шаблона, а документация
#    оператору всё ещё обещает, что она что-то делает.
unused = sorted(gw_allowlist - placeholders)
check("в списке envsubst нет переменных, которых нет в шаблоне", not unused, f"лишние: {unused}")

# 3. Иначе `set -u` в entrypoint.sh уронит контейнер на неустановленной переменной — с голым
#    "unbound variable" вместо задуманного сообщения.
declared = set(re.findall(r':\s*"\$\{(GW_[A-Z0-9_]+):=', entrypoint))
declared |= set(re.findall(r'\[\[ -n "\$\{(GW_[A-Z0-9_]+):-\}" \]\]', entrypoint))
undeclared = sorted(placeholders - declared)
check("у каждой подставляемой переменной есть дефолт или явная проверка", not undeclared,
      f"без дефолта: {undeclared}")

# 4. envsubst заменяет КАЖДОЕ перечисленное имя. Попади в список рантайм-переменная nginx
#    ($status, $binary_remote_addr, …) — её заменило бы пустой строкой, и формат лога или
#    лимитер тихо сломались бы.
nginx_owned = sorted(allowlist - gw_allowlist)
check("переменные nginx не попали в список envsubst", not nginx_owned, f"чужие: {nginx_owned}")

# 5. Номер счёта ездит в URL (/open-banking/v1.0/accounts/<IBAN>/statements) — путь не должен
#    растекаться в агрегацию логов.
fmt = re.search(r"log_format\s+gw\s+([\s\S]*?);", template)
if not fmt:
    check("формат лога найден", False, "log_format gw не найден")
else:
    body = fmt.group(1)
    # Только целые имена: $request_method и $request_time безопасны (пути в них нет), а
    # оба содержат "$request" подстрокой — простой поиск подстроки отверг бы их.
    leaked = [n for n in ("request", "uri", "args", "request_uri", "document_uri")
              if re.search(rf"\${n}(?![a-z_])", body)]
    check("формат лога не несёт путь запроса", not leaked, f"найдено: {leaked}")

# 6. Расшифрованное тело ответа не должно попадать на диск. Умолчание nginx —
#    `proxy_max_temp_file_size 1024m`: всё, что не поместилось в `proxy_buffers`,
#    дописывается во ВРЕМЕННЫЙ ФАЙЛ, и дописывается уже расшифрованным. Выписка по счёту
#    буферы перебирает, то есть при снятой директиве на диск контейнера ложились бы ровно
#    те данные, ради которых шлюз и построен.
#    ⚠ Сверяем ЗНАЧЕНИЕ, а не наличие: `proxy_max_temp_file_size 1m;` — это тоже директива
#    на месте, и это тоже мегабайт выписки на диске. Ноль — единственное значение, при
#    котором временный файл не создаётся вовсе.
#    ⚠ И комментарии срезаем ПЕРЕД поиском. Директива объяснена в шаблоне прозой, и в этой
#    прозе цитируется само умолчание `proxy_max_temp_file_size 1024m`; поиск по сырому
#    тексту цеплялся бы за цитату — то есть проверка утверждала бы про комментарий.
tmpfile = re.search(r"^\s*proxy_max_temp_file_size\s+([^;]+);",
                    re.sub(r"^\s*#.*$", "", template, flags=re.M), re.M)
check("расшифрованное тело не буферизуется на диск (proxy_max_temp_file_size 0)",
      tmpfile is not None and tmpfile.group(1).strip() == "0",
      "не найдено" if tmpfile is None else f"значение {tmpfile.group(1).strip()!r}, а не 0")

# 7. Шифрованный канал к непроверенному собеседнику — не то, ради чего всё делалось: потеря
#    любой из трёх директив превращает шлюз в нечто, разговаривающее с кем угодно на том IP.
for directive, pattern in (
    ("proxy_ssl_verify on", r"proxy_ssl_verify\s+on;"),
    ("proxy_ssl_trusted_certificate", r"proxy_ssl_trusted_certificate\s+\$\{GW_CA_BUNDLE\};"),
    ("proxy_ssl_name", r"proxy_ssl_name\s+\$\{GW_UPSTREAM_HOST\};"),
):
    check(f"проверка апстрима: {directive}", re.search(pattern, template) is not None, "директива не найдена")

# 8. DHT-BIGN — перенос ключа: компрометация долговременного ключа банка позже расшифрует
#    записанные сессии. DHE-BIGN эфемерен. Навязать порядок мы не можем (сервер вправе выбрать
#    свой), но заявить предпочтение обязаны именно так.
ciphers = re.search(r"proxy_ssl_ciphers\s+([^;]+);", template)
if not ciphers:
    check("шифронаборы найдены", False, "proxy_ssl_ciphers не найден")
else:
    lst = ciphers.group(1).split(":")
    dhe = next((i for i, c in enumerate(lst) if c.strip().startswith("DHE-BIGN")), -1)
    dht = next((i for i, c in enumerate(lst) if c.strip().startswith("DHT-BIGN")), -1)
    check("forward secrecy предлагается раньше переноса ключа",
          dhe >= 0 and dht >= 0 and dhe < dht, f"DHE на {dhe}, DHT на {dht}")

# 9. Шлюз никого не аутентифицирует — список путей И ЕСТЬ граница. `location /`, который
#    проксировал бы вместо отказа, превратил бы его в открытый релей к банку.
#    Комментарии срезаем: они обсуждают location'ы прозой, а утверждаем мы про директивы.
#    Делим по `location`, а не по скобкам: в телах есть `${GW_BURST}`, и скан `[^}]*`
#    остановился бы не на той скобке.
directives = re.sub(r"^\s*#.*$", "", template, flags=re.M)
blocks = re.split(r"\blocation\s+", directives)[1:]
proxied = []
for b in blocks:
    nxt = b.find("location")
    head = b if nxt == -1 else b[:nxt]
    if "proxy_pass" in head:
        proxied.append(re.match(r"(?:=\s+)?(\S+)", b).group(1))
# Маршруты к банку с версии #7 генерирует entrypoint.sh из GW_ALLOW и приносит
# include'ом. В САМОМ шаблоне проксирующих location быть не должно: вернувшийся сюда
# литеральный путь означал бы, что кто-то снова зашил API конкретного банка в образ —
# и, что хуже, обошёл проверку формата, которую генератор делает над GW_ALLOW.
check("в шаблоне нет захардкоженных проксирующих маршрутов", not proxied,
      f"найдены прямо в шаблоне: {sorted(proxied)}")
check("маршруты подключаются include'ом из сгенерированного файла",
      re.search(r"include\s+/tmp/crypto-gw\.routes\.conf;", directives) is not None,
      "include /tmp/crypto-gw.routes.conf; не найден")
# Пропажа этого include НЕ ломает ни сборку, ни старт: nginx поднимется, запросы пойдут, а
# каждая строка лога будет route=none. Оператор потеряет единственный признак того, какая
# ветка allowlist отработала, — и не узнает об этом, потому что всё зелёное.
check("метки маршрутов для лога тоже подключаются",
      re.search(r"include\s+/tmp/crypto-gw\.routes-map\.conf;", directives) is not None,
      "include /tmp/crypto-gw.routes-map.conf; не найден")
check("всё остальное отвергается", re.search(r"location\s+/\s*\{[^}]*return 404;", directives) is not None,
      "location / { … return 404; } не найден")

# 10. Самотест криптостека — секция 0 entrypoint.sh (#18, #42).
#
# ⚠ ЗАЧЕМ ТЕКСТОМ, а не запуском. Самотест исполняется только в собранном образе: он зовёт
# `bee2cmd` и `openssl` с движком, которых на машине разработчика нет. Значит поведение
# проверяет смоук job'а `image` — двадцать минут и вне PR-цикла, — и до #42 он был
# ЕДИНСТВЕННЫМ сторожем секции: удали её целиком, и быстрые проверки не заметили бы.
#
# ⚠ ЧЕМУ НАУЧИЛО РЕВЬЮ: «текст на месте» и «проверка работает» — РАЗНЫЕ утверждения, и
# первая версия этих проверок утверждала первое, называясь вторым. Пять обходов прошли её
# насквозь, каждый оставлял все проверки зелёными, а самотест мёртвым:
#   1. `die() { log ...; }` выше по файлу — все шесть `|| die` на месте, ни один не убивает;
#   2. второе присваивание `BEE2CMD_BIN="${GW_BEE2CMD:-$BEE2CMD_BIN}"` следом за литералом —
#      `re.search` видит только первое, переменная вернулась;
#   3. `GW_ALLOW_DUMP` с `!=` вместо `==` — самотест не исполняется НИ РАЗУ на боевом пути;
#   4. `[[ ! -x "$BEE2CMD_BIN" ]]` — условие вывернуто, подстрока цела;
#   5. `st alg 2>&1 || true` — код возврата подавлен, до `|| die` он не доходит.
# Отсюда правило ниже: сверяем ОПЕРАТОР ЦЕЛИКОМ И ДОСЛОВНО, а не наличие подстроки, и
# отдельно закрываем то, что дословностью не ловится (переопределение die, второе
# присваивание, ветка пропуска).


def logical_line(text, start):
    """Логическая строка bash, начиная с позиции start: до перевода строки без `\\`.

    Проверки самотеста устроены как `команда \\` + `|| die …` на следующей строке, то есть
    одним оператором на двух физических строках. Смотреть надо на весь оператор целиком:
    `die` на своей строке к соседнему вызову отношения не имеет.

    ⚠ Известное ограничение: перенос считается по ОДНОМУ `\\` перед `\\n`, поэтому строка,
    оканчивающаяся литеральным экранированным слешем (`\\\\`), была бы склеена со следующей
    ошибочно. В `entrypoint.sh` таких строк нет — проверено, — а городить разбор чётности
    ради несуществующего случая дороже, чем назвать его здесь. Так же не распознаётся
    перенос БЕЗ слеша (`cmd ||` в конце строки): он дал бы ложный КРАСНЫЙ, то есть
    сломанный CI с понятной причиной, а не тихий пропуск.
    """
    j = start
    while True:
        j = text.find("\n", j)
        if j == -1:
            return text[start:]
        if text[j - 1] != "\\":
            return text[start:j]
        j += 1


# Подавление кода возврата: любая из этих форм превращает фатальную проверку в
# необязательную, не тронув ни одного символа в `|| die`.
SUPPRESSORS = (r"\|\|\s*true\b", r"\|\|\s*:", r";\s*true\b", r"\|\|\s*exit\s+0\b")


def selftest_gate(label, operator):
    """Оператор самотеста на месте ДОСЛОВНО, и его провал заканчивается `die`.

    operator — полный текст оператора, как он написан в `entrypoint.sh`, без завершающего
    `\\`. Сверяем именно дословно: подстрока `-x "$BEE2CMD_BIN"` совпала бы и с вывернутым
    `[[ ! -x "$BEE2CMD_BIN" ]]`, а `st alg 2>&1` — с `st alg 2>&1 || true`.
    """
    hits = entrypoint_code.count(operator)
    check(f"самотест: {label} — оператор на месте дословно", hits == 1,
          "оператор не найден" if hits == 0 else
          f"оператор встречается {hits} раз(а) — сверять нечего, неясно какой из них рабочий")
    if hits != 1:
        return
    line = logical_line(entrypoint_code, entrypoint_code.index(operator))
    flat = " ".join(line.split())
    suppressed = [s for s in SUPPRESSORS if re.search(s, line)]
    check(f"самотест: провал «{label}» роняет контейнер",
          re.search(r"\|\|\s*die\b", line) is not None and not suppressed,
          f"подавлен код возврата ({suppressed}): {flat[:140]}" if suppressed
          else f"нет `|| die` в операторе: {flat[:140]}")


# Обе половины самотеста, и они проверяют РАЗНОЕ (README § «Самотестирование криптостека»):
# первые три — статически слинкованный bee2cmd, вторые три — тот самый рабочий стек
# nginx → libssl → libbee2evp.so, которым пойдёт трафик.
selftest_gate("бинарь bee2cmd на месте", '[[ -x "$BEE2CMD_BIN" ]]')
selftest_gate("контрольные примеры алгоритмов (st alg)",
              'st_out="$("$BEE2CMD_BIN" st alg 2>&1)"')
selftest_gate("самотест ДСЧ (st rng)", 'st_out="$("$BEE2CMD_BIN" st rng 2>&1)"')
selftest_gate("движок bee2evp опрашивается",
              'engine_out="$("$OPENSSL_BIN" engine -t bee2evp 2>&1)"')
selftest_gate("движок bee2evp доступен", '[[ "$engine_out" == *available* ]]')
selftest_gate("рабочий стек предлагает криптонабор BTLS",
              '"$OPENSSL_BIN" ciphers -v \'ALL:eNULL\' 2>/dev/null'
              " | grep -q 'DHE-BIGN-WITH-BELT-CTR-MAC-HBELT'")

# ⚠ `die` и `log` — фундамент всех шести операторов выше. Переопредели `die` одной строкой
# (`die() { log "..."; }`), и каждый `|| die` останется на месте, ничего не убивая: шлюз
# стартует со сломанной криптографией, печатая бодрый лог. Это самый дешёвый из найденных
# ревью обходов — одна строка, и весь сторож выше становится декорацией.
for fn in ("die", "log"):
    defs = len(re.findall(rf"^\s*{fn}\s*\(\)\s*\{{", entrypoint_code, re.M))
    check(f"`{fn}` определена ровно один раз (переопределение обнулило бы самотест)",
          defs == 1, f"определений найдено: {defs}")

# ⚠ Пути к bee2cmd и openssl обязаны быть литералами, и присваивание — РОВНО ОДНО.
# Здесь была переменная `GW_BEE2CMD` — ради теста «провал самотеста роняет контейнер», — и
# ревью показало, чем она была: не выключателем, а способом ПОДДЕЛАТЬ УСПЕХ. Заглушка с
# `exit 0` печатает ту же строку «— OK», неотличимую от честной.
# ⚠ Считаем ВСЕ присваивания, а не первое: `re.search` пропускал вторую строку
# `BEE2CMD_BIN="${GW_BEE2CMD:-$BEE2CMD_BIN}"`, которая возвращала переменную дословно и
# оставляла проверку зелёной. Именно она и определяет значение к моменту вызова.
for var in ("BEE2CMD_BIN", "OPENSSL_BIN"):
    assigns = re.findall(rf"^{var}=(.+)$", entrypoint_code, re.M)
    if len(assigns) != 1:
        check(f"путь к {var} присваивается ровно один раз", False,
              f"присваиваний найдено: {len(assigns)} — {assigns}")
        continue
    value = assigns[0].strip()
    check(f"путь к {var} зашит, а не берётся из окружения",
          "$" not in value and value.strip('"\'').startswith("/"),
          f"значение подставляется извне: {value}")

# ⚠ Самотест обязан ИСПОЛНЯТЬСЯ на боевом пути. Вся секция 0 завёрнута в ветку `else`
# единственного законного исключения — `GW_ALLOW_DUMP=1`, режима выгрузки конфигурации,
# который трафик не обслуживает никогда. Поменяй в условии `==` на `!=` — и самотест не
# отработает ни разу при обычном старте, а все проверки выше останутся зелёными: операторы
# на месте, `die` на месте, просто ветка не та. Поэтому условие сверяется дословно, а
# положение гейтов — по смещению в файле.
# ⚠ Иголка включает СЛЕДУЮЩУЮ строку — сообщение о пропуске. Само условие
# `GW_ALLOW_DUMP == 1` встречается в файле ДВАЖДЫ (второй раз — там, где дамп собственно
# выходит), и поиск по одному условию, не найдя испорченное первое, спокойно нашёл бы
# второе и позеленел. Проверено мутацией: она правит только первое вхождение.
DUMP_IF = ('if [[ "${GW_ALLOW_DUMP:-}" == 1 ]]; then\n'
           "  log 'самотест пропущен: GW_ALLOW_DUMP")
dump_at = entrypoint_code.find(DUMP_IF)
check("ветка пропуска самотеста — дословно GW_ALLOW_DUMP == 1", dump_at != -1,
      f"не найдено: {DUMP_IF}")
selftest_body = ""
if dump_at != -1:
    else_at = entrypoint_code.find("\nelse\n", dump_at)
    gate_at = entrypoint_code.find('[[ -x "$BEE2CMD_BIN" ]]')
    check("самотест лежит в ветке else, то есть исполняется при обычном старте",
          else_at != -1 and gate_at > else_at,
          "гейты самотеста не находятся в ветке else этого условия")
    if else_at != -1:
        # Тело секции 0 — от `else` до закрывающего `fi`. Берём по КОДУ, а не по маркеру
        # `# --- 0.` в комментарии: маркер живёт в прозе, а проза переживает свой код.
        # Вложенных `if` внутри нет, поэтому первый `fi` и есть закрывающий; появись
        # вложенность — область обрежется, строка успеха потеряется и проверка ниже
        # покраснеет. Красный в безопасную сторону.
        fi_at = entrypoint_code.find("\nfi\n", else_at)
        selftest_body = entrypoint_code[else_at:fi_at if fi_at != -1 else len(entrypoint_code)]

# ⚠ Строки успеха — часть контракта с оператором, а не украшение лога. README показывает их
# как признак того, что самотест прошёл; печатай код другое — оператор ищет в логе то, чего
# там нет, и делает вывод, что самотест не отработал. Проверка написана потому, что
# расхождение УЖЕ БЫЛО: README обещал «самотест криптостека: …», код печатал «самотест ядра
# bee2: …», и после #38 строк стало две вместо одной.
#
# ⚠ Сравниваем РАВЕНСТВО МНОЖЕСТВ, а не вхождение. Прежняя формулировка («каждая строка
# README печатается кодом») проходила ВХОЛОСТУЮ на пустом README: нет строк — нечему
# разойтись. Источник истины теперь код, а он пустым быть не может — его непустоту держат
# шесть проверок выше. Заодно сверяется ПРЕФИКС: он берётся из самой `log()`, а не
# зашивается сюда, иначе смена `[crypto-gw]` на что угодно осталась бы незамеченной, хотя
# именно префикс оператор глазами и ищет.
fmt = re.search(r"^\s*log\(\)\s*\{\s*printf\s+'([^']*)%s", entrypoint_code, re.M)
section = re.search(r"^## Самотестирование криптостека\n(.*?)(?=^## )", readme, re.M | re.S)
if not fmt:
    check("формат log() разобран", False, "не нашёл printf-формат в определении log()")
elif not section:
    check("README: раздел про самотест найден", False,
          "нет раздела «## Самотестирование криптостека»")
else:
    fence = re.search(r"^```\n(.*?)^```", section.group(1), re.M | re.S)
    promised = [ln for ln in fence.group(1).splitlines() if ln.strip()] if fence else []
    # Строки успеха — статические `log '…'` на «— OK» ВНУТРИ ТЕЛА САМОТЕСТА. Область важна:
    # по всему файлу на «— OK» оканчивается ещё и строка про цепочку ГосСУОК из секции 2,
    # которую этот раздел README не показывает и показывать не должен.
    printed = re.findall(r"^\s*log\s+'([^']*— OK)'\s*$", selftest_body, re.M)
    rendered = sorted(fmt.group(1) + p for p in printed)
    check("строки успеха самотеста: README и entrypoint.sh совпадают дословно",
          sorted(promised) == rendered,
          f"README: {sorted(promised)} ≠ код: {rendered}")

# ⚠ Список возможностей в KNOWN_GW_VARS — КОНТРАКТ С ОПЕРАТОРОМ, а не справка (#75).
# По нему потребитель отличает запинённую старую сборку от неверной настройки: задал
# переменную, её нет в строке — образ её не знает. Стоило полдня чужого времени, прежде
# чем строка появилась (#64).
#
# Контракт держится, только пока список СОВПАДАЕТ с тем, что код реально читает. Разъехаться
# он может в обе стороны, и обе плохи:
#   - переменная в коде есть, в списке нет → оператор считает её неподдерживаемой и не
#     задаёт; сборка при этом её понимает. Хуже: она попадёт в «ВНИМАНИЕ: неизвестна»,
#     то есть образ соврёт о себе сам;
#   - переменная в списке есть, в коде нет → оператор задаёт её и ждёт эффекта, которого
#     не будет. Ровно тот молчаливый отказ, ради которого список и заведён.
# Поэтому сверяем РАВЕНСТВОМ МНОЖЕСТВ, а не вхождением.
known = re.search(r"^KNOWN_GW_VARS='([^']*)'", entrypoint_code, re.M)
if not known:
    check("KNOWN_GW_VARS найден в entrypoint.sh", False, "не нашёл присваивание списка")
else:
    declared = set(known.group(1).split())
    # ⚠ САМУ СТРОКУ СПИСКА ИЗ ПОИСКА ВЫРЕЗАЕМ, и это не мелочь: без этого проверка
    # «список не обещает лишнего» вырождалась в тавтологию — имя, вписанное в список,
    # находилось поиском в нём же и считалось используемым. Показано мутацией при вводе:
    # дописанная `GW_PHANTOM` проходила зелёной. Ровно тот случай, ради которого в этом
    # файле стоит предупреждение про сверку на вхождение подстроки.
    code_wo_list = entrypoint_code.replace(known.group(0), "")
    # Что код реально читает: `${GW_X:...}`, `${GW_X}`, `"${GW_X`, `$GW_X` — плюс шаблон.
    # ⚠ ТРИ файла, а не два, и третий добавлен по ревью. `healthcheck.sh` читает
    # `GW_LISTEN` напрямую, и до этой правки в область поиска не входил. Сегодня совпадение
    # случайное — `GW_LISTEN` попадает в `used` через entrypoint. Появись завтра переменная,
    # которую читает ТОЛЬКО healthcheck, и проверка «список не умалчивает» её не заметила бы,
    # а рантайм из #75 объявил бы её «НЕИЗВЕСТНОЙ этой сборке» — то есть изделие соврало бы
    # о себе, ссылаясь на нашу же проверку.
    used = set(re.findall(r"\bGW_[A-Z0-9_]+", code_wo_list)) | \
           set(re.findall(r"\bGW_[A-Z0-9_]+", template)) | \
           set(re.findall(r"\bGW_[A-Z0-9_]+", healthcheck))
    # Служебное имя самого списка в счёт не идёт.
    used -= {"KNOWN_GW_VARS"}
    # ⚠ И сама строка обязана ПЕЧАТАТЬСЯ. Список, который никуда не выводится, — переменная
    # без читателя: потребитель по её отсутствию отличает старую сборку (#75), а проверки
    # выше сверяют только содержимое. Сними кто-нибудь `log` — контракт исчез бы молча.
    # ⚠ И ВТОРАЯ ПОЛОВИНА #75 — предупреждение о незнакомой `GW_*`. Именно она закрывает
    # исходный случай: потребитель задал переменную, которой сборка не знает, и не получил
    # ни звука. Список возможностей помогает догадаться, предупреждение — говорит прямо.
    # Сними цикл — проверки выше остались бы зелёными (список-то на месте), а молчание
    # вернулось бы. Поведение этой ветки отдельно утверждает смоук в job `image`.
    # ⚠ Оператор сверяется ЦЕЛИКОМ И ДОСЛОВНО, а не двумя независимыми фактами. Первая
    # редакция проверяла «цикл есть» и «слово НЕИЗВЕСТНА где-то есть» — и тестировщик
    # показал прогоном, что замена `log` на `die` проходит зелёной: оба факта остаются
    # истинными, а инвариант LOUD-not-fatal умирает. Любая лишняя `GW_*` в общем блоке
    # environment docker-compose роняла бы контейнер, и обязательный чек `ci` молчал бы.
    # Тот же урок, что у самотеста (шапка файла): сверка на вхождение доказывает, что
    # текст написан, и ничего — о том, что он работает.
    WARN_STMT = 'log "ВНИМАНИЕ: переменная $_gw_var этой сборке НЕИЗВЕСТНА и будет проигнорирована"'
    check("незнакомая GW_-переменная вызывает предупреждение",
          re.search(r"for _gw_var in \$\{!GW_@\}; do", entrypoint_code) is not None
          and WARN_STMT in entrypoint_code,
          f"не нашёл дословно: {WARN_STMT}")
    # ⚠ И предупреждение обязано остаться именно `log`, не `die`: других вызовов die/exit
    # внутри цикла быть не должно. Область — от `for _gw_var` до `unset _gw_var`.
    loop_m = re.search(r"for _gw_var in \$\{!GW_@\}; do(.*?)unset _gw_var",
                       entrypoint_code, re.S)
    check("предупреждение о незнакомой переменной НЕ фатально (log, а не die)",
          loop_m is not None and not re.search(r"\b(die|exit)\b", loop_m.group(1)),
          "в цикле предупреждения найден die/exit — LOUD, not fatal нарушен")
    check("состав возможностей печатается при старте",
          re.search(r'^log "понимает переменные: \$KNOWN_GW_VARS"$', entrypoint_code, re.M)
          is not None,
          "не нашёл строку log \"понимает переменные: $KNOWN_GW_VARS\"")
    check("список возможностей не обещает лишнего (в списке есть, в коде нет)",
          not (declared - used), f"лишние в списке: {sorted(declared - used)}")
    check("список возможностей не умалчивает (в коде есть, в списке нет)",
          not (used - declared), f"не названы в списке: {sorted(used - declared)}")

if failures:
    print(f"\nпровалено проверок: {len(failures)}", file=sys.stderr)
    sys.exit(1)
print("\nвсе проверки конфигурации пройдены")
